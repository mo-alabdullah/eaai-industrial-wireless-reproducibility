#!/usr/bin/env python3
"""STAGE I-A - exact slot-level radio-allocation benchmark on visited states.

A single reference trajectory per (regime, seed) is generated by the deployable heuristic
EDF-StaleBeam-MinFeasible. At every measurement slot the state is frozen and the exact optimum is
computed under two information sets and two scheduling scopes, so heuristic and optimiser are always
compared on IDENTICAL states. Development seeds 10001-10008 only.
"""
from __future__ import annotations
import argparse, csv, json, os, sys, time
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, "..", "..", "07_simulation"))

import numpy as np
from evaluation import journal_cfg
from baselines_v2 import ComponentAgent
from m2.env import M2Env, IDLE
from optimization.grids import with_grid
from optimization.capture import freeze
from optimization.radio import (solve_exact_radio, solve_exact_radio_fixed_demand,
                                realised_success, Allocation)

SEEDS = list(range(10001, 10009))
REGIMES = {                      # I-C benchmark states
    "R1_nominal":   dict(dist=1.0, age=1, load=0.40),
    "R2_range":     dict(dist=2.0, age=1, load=0.40),
    "R3_aged":      dict(dist=2.0, age=5, load=0.40),
    "R4_moderate":  dict(dist=1.5, age=3, load=0.40),
}
GRID_KEYS = ("G0_icame", "G2_wide10")
T_SLOTS = 250
RES = os.path.normpath(os.path.join(HERE, "..", "results"))
JSONL = os.path.join(RES, "stage_i_radio_v2.jsonl")
CSV = os.path.join(RES, "stage_i_radio_v2.csv")


def _tok_kbp(t):
    return (int(t[0][1:]), int(t[1][1:]), int(t[2][1:]))


def run_one(job):
    regime, gk, seed = job
    cfg = journal_cfg(REGIMES[regime]["load"], t_meas=T_SLOTS,
                      hall_x=300.0 * REGIMES[regime]["dist"],
                      hall_y=150.0 * REGIMES[regime]["dist"],
                      d_csi_slots=REGIMES[regime]["age"])
    cfg = with_grid(cfg, gk)
    env = M2Env(cfg, 700_000_000 + seed * 100)
    ag = ComponentAgent(env, seed=seed, scheduler="EDF",
                        beam_rule="StaleBest", power_rule="MinFeasible-Stale")
    env.reset(); ag.reset()
    rec = []
    obs = env.begin_slot(); done = False
    t_exact = 0.0
    while not done:
        st = freeze(env)
        toks = ag.act(obs)
        used = [(_tok_kbp(t), n) for n, t in enumerate(toks) if t != IDLE]
        h_alloc = Allocation(tokens=[None] * st.N)
        for (k, b, p), n in used:
            h_alloc.tokens[n] = (k, b, p)
        h_alloc.served = len(used)
        h_alloc.power_w = sum(st.power_grid[p] for (_, _, p), _ in used)
        edf_set = sorted({k for (k, _, _), _ in used})

        demand = {}
        for (k, _, _), _n in used:
            demand[k] = demand.get(k, 0) + 1

        t0 = time.perf_counter()
        # pure radio allocation: scheduling decision (which packets) held COMPLETELY fixed
        ex_fix_aged = solve_exact_radio_fixed_demand(st, demand, use_true=False) if demand else None
        ex_fix_true = solve_exact_radio_fixed_demand(st, demand, use_true=True) if demand else None
        ex_aged_edf  = solve_exact_radio(st, use_true=False, allowed=edf_set or None)
        ex_aged_free = solve_exact_radio(st, use_true=False)
        ex_true_free = solve_exact_radio(st, use_true=True)
        t_exact += time.perf_counter() - t0

        row = dict(
            slot=env.t,
            h_served=h_alloc.served, h_power=h_alloc.power_w,
            h_real_ok=realised_success(st, h_alloc),
            # PURE radio allocation (same packets, same devices, same counts)
            x_power=(ex_fix_aged.power_w if ex_fix_aged else float("nan")),
            x_real_ok=(realised_success(st, ex_fix_aged) if ex_fix_aged else 0),
            x_nodes=(ex_fix_aged.nodes if ex_fix_aged else 0),
            xo_power=(ex_fix_true.power_w if ex_fix_true else float("nan")),
            xo_real_ok=(realised_success(st, ex_fix_true) if ex_fix_true else 0),
            # exact, aged CSI, EDF-scheduled device set (isolates radio allocation)
            a_served=ex_aged_edf.served, a_power=ex_aged_edf.power_w,
            a_real_ok=realised_success(st, ex_aged_edf),
            a_at_h=ex_aged_edf.frontier.get(h_alloc.served, float("nan")),
            # exact, aged CSI, free device choice (adds intra-slot scheduling)
            f_served=ex_aged_free.served, f_power=ex_aged_free.power_w,
            f_real_ok=realised_success(st, ex_aged_free),
            f_at_h=ex_aged_free.frontier.get(h_alloc.served, float("nan")),
            # exact, current CSI, free (ORACLE / NON-DEPLOYABLE upper bound)
            o_served=ex_true_free.served, o_power=ex_true_free.power_w,
            o_real_ok=realised_success(st, ex_true_free),
            o_at_h=ex_true_free.frontier.get(h_alloc.served, float("nan")),
            nodes=ex_aged_edf.nodes + ex_aged_free.nodes + ex_true_free.nodes,
            n_elig=int(sum(1 for k in range(st.K) if st.queue_len[k] > 0)),
        )
        rec.append(row)
        nxt, rp, rb, cost, done, info = env.commit_action(toks)
        obs = nxt if nxt is not None else obs
    return dict(regime=regime, grid=gk, seed=seed, slots=len(rec),
                cpu_exact_s=t_exact, rows=rec,
                dist_scale=REGIMES[regime]["dist"], d_csi=REGIMES[regime]["age"],
                load=REGIMES[regime]["load"])


def jobs_all():
    return [(r, g, s) for r in REGIMES for g in GRID_KEYS for s in SEEDS]


def key(j): return "|".join(str(x) for x in j)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--budget", type=float, default=150.0)
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--csv", action="store_true")
    a = ap.parse_args()
    os.makedirs(RES, exist_ok=True)
    js = jobs_all()
    if a.csv:
        out = []
        for line in open(JSONL):
            if not line.strip():
                continue
            d = json.loads(line)
            for r in d["rows"]:
                r2 = dict(regime=d["regime"], grid=d["grid"], seed=d["seed"],
                          dist_scale=d["dist_scale"], d_csi=d["d_csi"], load=d["load"])
                r2.update(r); out.append(r2)
        cols = list(out[0].keys())
        with open(CSV, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore"); w.writeheader(); w.writerows(out)
        print(f"CSV: {len(out)} slot rows -> {CSV}"); return
    have = set()
    if os.path.exists(JSONL):
        for x in open(JSONL):
            if x.strip():
                d = json.loads(x); have.add(key((d["regime"], d["grid"], d["seed"])))
    todo = [j for j in js if key(j) not in have]
    print(f"total={len(js)} done={len(have)} todo={len(todo)}")
    if not todo:
        print("ALL DONE"); return
    t0 = time.time(); n = 0
    with Pool(a.workers) as pool, open(JSONL, "a") as f:
        for res in pool.imap_unordered(run_one, todo, chunksize=1):
            f.write(json.dumps(res) + "\n"); f.flush(); n += 1
            if time.time() - t0 > a.budget:
                break
    print(f"completed {n} this call in {time.time()-t0:.1f}s; remaining={len(todo)-n}")


if __name__ == "__main__":
    main()
